// Generates the diagnostic message table and its translations from the pinned
// TypeScript sources (tsc/internal/diagnostics).
import { execFileSync } from 'node:child_process';
import { mkdirSync, readFileSync, readdirSync, rmSync, writeFileSync } from 'node:fs';
import { join, resolve } from 'node:path';
import { gunzipSync } from 'node:zlib';

const root = resolve(import.meta.dirname, '..');
const upstream = resolve(root, '../../upstream/TypeScript/tsc/internal/diagnostics');
const out = join(root, 'src/compiler');
const header = '// Generated by scripts/generate-diagnostics.mjs. Do not edit.\n\n';

// Message texts and translations never contain a line feed, so it separates them.
const separator = '\n';

/** Decodes a Go interpreted string literal. */
function unquote(literal) {
  let result = '';
  for (let i = 1; i < literal.length - 1; i++) {
    const c = literal[i];
    if (c !== '\\') {
      result += c;
      continue;
    }
    const e = literal[++i];
    const simple = { a: '\x07', b: '\b', f: '\f', n: '\n', r: '\r', t: '\t', v: '\v', '\\': '\\', "'": "'", '"': '"' };
    if (e in simple) result += simple[e];
    else if (e === 'x' || e === 'u' || e === 'U') {
      const length = e === 'x' ? 2 : e === 'u' ? 4 : 8;
      result += String.fromCodePoint(parseInt(literal.slice(i + 1, i + 1 + length), 16));
      i += length;
    } else throw new Error(`unsupported escape \\${e} in ${literal}`);
  }
  return result;
}

const categories = ['CategoryWarning', 'CategoryError', 'CategorySuggestion', 'CategoryMessage'];
const flagNames = ['reportsUnnecessary', 'elidedInCompatibilityPyramid', 'reportsDeprecated'];

function readMessages() {
  const source = readFileSync(join(upstream, 'diagnostics_generated.go'), 'utf8');
  const string = '("(?:[^"\\\\]|\\\\.)*")';
  const pattern = new RegExp(
    `^var (\\w+) = &Message\\{code: (\\d+), category: (\\w+), key: ${string}, text: ${string}((?:, \\w+: true)*)\\}$`,
    'gm',
  );
  const messages = [];
  for (const [, name, code, category, key, text, options] of source.matchAll(pattern)) {
    let flags = categories.indexOf(category);
    if (flags < 0) throw new Error(`unknown category ${category}`);
    for (const [, option] of options.matchAll(/, (\w+): true/g)) {
      const bit = flagNames.indexOf(option);
      if (bit < 0) throw new Error(`unknown message option ${option}`);
      flags |= 4 << bit;
    }
    messages.push({ name, code: Number(code), flags, key: unquote(key), text: unquote(text) });
  }
  const declared = source.match(/^var \w+ = &Message\{/gm).length;
  if (messages.length !== declared) throw new Error(`parsed ${messages.length} of ${declared} messages`);
  for (let i = 1; i < messages.length; i++) {
    if (messages[i].code <= messages[i - 1].code) throw new Error('messages are not sorted by code');
  }
  return messages;
}

/** The supported locales in matcher order, after English. */
function readLocaleTags() {
  const source = readFileSync(join(upstream, 'loc_generated.go'), 'utf8');
  return [...source.matchAll(/language\.MustParse\("([\w-]+)"\)/g)].map((m) => m[1]);
}

function joined(texts) {
  for (const text of texts) if (text.includes(separator)) throw new Error(`separator in ${JSON.stringify(text)}`);
  // Invisible control and bidirectional formatting characters are escaped so the
  // generated source shows them.
  return JSON.stringify(texts.join(separator)).replace(
    // oxlint-disable-next-line no-control-regex -- matching these characters is the point
    /[\u0000-\u001f\u007f-\u009f\u200b-\u200f\u202a-\u202e\u2066-\u2069\ufeff]/g,
    (c) => '\\u' + c.charCodeAt(0).toString(16).padStart(4, '0'),
  );
}

function rows(values, perRow) {
  const lines = [];
  for (let i = 0; i < values.length; i += perRow) lines.push('  ' + values.slice(i, i + perRow).join(', ') + ',');
  return lines.join('\n');
}

function messagesModule(messages) {
  const members = messages.map((m, i) => `  ${m.name} = ${i},`).join('\n');
  return `${header}/** Every diagnostic message, numbered in code order. */
export const enum Diagnostics {
${members}
}

export const messageCount = ${messages.length};

/** Message codes, indexed by message. */
export const messageCodes: Int32Array = new Int32Array([
${rows(
  messages.map((m) => m.code),
  16,
)}
]);

/** The category (bits 0-1), then reportsUnnecessary, elidedInCompatibilityPyramid and reportsDeprecated bits. */
export const messageFlags: Uint8Array = new Uint8Array([
${rows(
  messages.map((m) => m.flags),
  40,
)}
]);

/** Message keys, in message order, separated by line feeds. */
export const messageKeys = ${joined(messages.map((m) => m.key))};

/** English message texts, in message order, separated by line feeds. */
export const messageTexts = ${joined(messages.map((m) => m.text))};
`;
}

/** `zh-CN` -> `zhCN`, the name of its texts constant. */
function localeName(tag) {
  return tag.replace('-', '');
}

/** `zh-CN` -> `ZhCN`, its `Locale` member. */
function localeMember(tag) {
  return tag[0].toUpperCase() + localeName(tag).slice(1);
}

function localesModule(tags) {
  const members = tags.map((tag, i) => `  ${localeMember(tag)} = ${i + 1},`).join('\n');
  const imports = tags.map((tag) => `import { ${localeName(tag)} } from './locales/${tag}.js';`).join('\n');
  const cases = tags.map((tag) => `    case Locale.${localeMember(tag)}:\n      return ${localeName(tag)};`).join('\n');
  return `${header}${imports}

/** The languages diagnostics are translated into, in tsgo's matcher order. */
export const enum Locale {
  /** Untranslated English. */
  Default = 0,
${members}
}

/** The BCP 47 tag of each locale, indexed by \`Locale\`. */
export const localeTags: readonly string[] = ['en', ${tags.map((tag) => `'${tag}'`).join(', ')}];

/** The translated texts of \`locale\` in message order, separated by line feeds; empty where untranslated. */
export function translations(locale: Locale): string {
  switch (locale) {
${cases}
    default:
      return '';
  }
}
`;
}

function translationModule(tag, messages) {
  const translated = JSON.parse(gunzipSync(readFileSync(join(upstream, 'loc', `${tag}.json.gz`))));
  const texts = messages.map((m) => translated[m.key] ?? '');
  const count = texts.filter((text) => text !== '').length;
  if (texts.some((text, i) => text === '' && messages[i].key in translated)) throw new Error('empty translation');
  return {
    count,
    source: `${header}/** ${tag} message texts, in message order, separated by line feeds; empty where untranslated. */
export const ${localeName(tag)} = ${joined(texts)};
`,
  };
}

const messages = readMessages();
const tags = readLocaleTags();
const files = new Map([
  ['diagnostic-messages.ts', messagesModule(messages)],
  ['diagnostic-locales.ts', localesModule(tags)],
]);
rmSync(join(out, 'locales'), { recursive: true, force: true });
mkdirSync(join(out, 'locales'));
const available = readdirSync(join(upstream, 'loc'))
  .filter((name) => name.endsWith('.json.gz'))
  .map((name) => name.replace('.json.gz', ''));
if (available.sort().join() !== [...tags].sort().join()) throw new Error('locale files do not match loc_generated.go');
const counts = [];
for (const tag of tags) {
  const { count, source } = translationModule(tag, messages);
  files.set(`locales/${tag}.ts`, source);
  counts.push(`${tag} ${count}`);
}
for (const [name, text] of files) writeFileSync(join(out, name), text);
execFileSync(
  resolve(root, '../../node_modules/.bin/oxfmt'),
  [...files.keys()].map((name) => join(out, name)),
  { stdio: 'inherit' },
);
console.log(`${messages.length} messages; translations: ${counts.join(', ')}`);
