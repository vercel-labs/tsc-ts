// Generates the types of tsc-ts's public API (src/library) from TypeScript 7's API package at the pinned
// TypeScript commit, so that they name and number everything as TypeScript 7's API does:
//
//   src/library/enums.generated.ts             the enums of packages/typescript/src/enums, and
//                                              TypeFormatFlags from src/compiler/checker-types.ts
//   src/library/compiler-options.generated.ts  CompilerOptions (packages/typescript/src/api)
//   src/library/ast.generated.ts               the node interfaces, from tools/scripts/tsc/ast.json through
//                                              the schema model (tools/scripts/tsc/schema.ts), as
//                                              tools/scripts/tsc/generate-ts-ast.ts generates them, with tsc-ts's
//                                              NodeList and ModifierList in place of NodeArray, without
//                                              brand members, and with members typed as tsc-ts's nodes
//                                              hold them
//
// Usage: node scripts/generate-api.mjs [--check]
//
// With --check, writes nothing and fails if a generated file differs from what it would write.
import { execFileSync } from 'node:child_process';
import { mkdtempSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join, resolve } from 'node:path';
import { pathToFileURL } from 'node:url';
import { nullable } from './ast-nullable.mjs';

const root = resolve(import.meta.dirname, '..');
const repo = resolve(root, '../..');
const upstream = join(repo, 'upstream/TypeScript');
const apiPackage = join(upstream, 'packages/typescript/src');
const scripts = join(upstream, 'tools/scripts/tsc');
const libraryDir = join(root, 'src/library');
const check = process.argv.includes('--check');

/** An upstream file's text, with LF line ends (upstream's API package uses CRLF). */
const readUpstream = (path) => readFileSync(path, 'utf8').replace(/\r\n/g, '\n');

const notice = (source) =>
  `// Generated by scripts/generate-api.mjs from ${source} (TypeScript 7.1.0-beta).\n` +
  `// TypeScript is Copyright Microsoft Corporation, licensed under Apache-2.0. Do not edit.\n`;

// Enums, in the order the public API exports them.
const enumFiles = [
  'syntaxKind',
  'nodeFlags',
  'modifierFlags',
  'tokenFlags',
  'symbolFlags',
  'typeFlags',
  'objectFlags',
  'elementFlags',
  'signatureFlags',
  'signatureKind',
  'typePredicateKind',
  'nodeBuilderFlags',
  'scriptTarget',
  'moduleKind',
  'moduleResolutionKind',
  'moduleDetectionKind',
  'scriptKind',
  'languageVariant',
  'jsxEmit',
  'newLineKind',
  'diagnosticCategory',
  'internalSymbolName',
];

function generateEnums() {
  const parts = [notice('TypeScript packages/typescript/src/enums and src/compiler/checker-types.ts')];
  for (const name of enumFiles) {
    const text = readUpstream(join(apiPackage, 'enums', name + '.enum.ts'));
    parts.push(text.replace(/^\/\/ Code generated[^\n]*\n+/, '').trimEnd() + '\n');
  }
  // TypeScript 7's API package has no TypeFormatFlags; typeToString takes tsgo's, which tsc-ts has.
  const checkerTypes = readFileSync(join(root, 'src/compiler/checker-types.ts'), 'utf8');
  const match = /^export const enum TypeFormatFlags \{\n[\s\S]*?^\}\n/m.exec(checkerTypes);
  if (match === null) throw new Error('TypeFormatFlags not found in checker-types.ts');
  parts.push(match[0].replace('export const enum', 'export enum'));
  return parts.join('\n');
}

function generateCompilerOptions() {
  const text = readUpstream(join(apiPackage, 'api/compilerOptions.generated.ts'));
  const pathImport = /^import type \{[^}]*\} from "\.\.\/ast\/index\.ts";\n/m;
  if (!pathImport.test(text)) throw new Error('compilerOptions.generated.ts no longer imports its path types');
  const body = text
    .replace(
      /^import type \{ (\w+) \} from "#enums\/\w+";\n/gm,
      (_, name) => `import type { ${name} } from './enums.generated.js';\n`,
    )
    // TypeScript 7's API brands paths as rooted; tsc-ts's API takes them as strings.
    .replace(
      pathImport,
      'type RootedPath = string;\ntype RootedFilePath = string;\ntype RootedDirectoryPath = string;\n',
    )
    // The enums are exported from enums.generated.ts.
    .replace(/^export \{ \w+ \} from "#enums\/\w+";\n/gm, '');
  return notice('TypeScript packages/typescript/src/api/compilerOptions.generated.ts') + '\n' + body;
}

// Where tsc-ts's nodes hold less than ast.json declares, the interfaces declare what the nodes hold.
// NoSubstitutionTemplateLiteral stores no raw text (TypeScript 7's API gives undefined there): the base
// declares it optional, and the kinds that store it declare it again.
const unstoredBaseFields = new Map([
  ['TemplateLiteralLikeNodeBase.RawText', ['TemplateHead', 'TemplateMiddle', 'TemplateTail']],
]);
const redeclared = new Set(
  [...unstoredBaseFields].flatMap(([field, kinds]) => kinds.map((kind) => `${kind}.${field.split('.')[1]}`)),
);
// Members of a kind that shares its node with others, where the kind always or never has them: a case
// clause always has an expression and a default clause never does.
const variantMembers = new Map([
  ['CaseClause.Expression', 'required'],
  ['DefaultClause.Expression', 'absent'],
]);

// Member types ast.json gives narrower than the values tsgo's and tsc-ts's parsers store: `declare
// global` is a module declaration with the `global` keyword.
const memberTypes = new Map([
  ['ModuleDeclaration.Keyword', 'SyntaxKind.ModuleKeyword | SyntaxKind.NamespaceKeyword | SyntaxKind.GlobalKeyword'],
]);

// The node interfaces. The functions below follow tools/scripts/tsc/generate-ts-ast.ts (generateAstGenerated).
async function generateAst() {
  // schema.ts takes the repository root from tools/scripts/gen/utils.mts, whose own imports are not
  // installed here; a copy of it gets the root directly.
  const schemaDir = mkdtempSync(join(tmpdir(), 'tsc-ts-schema-'));
  const schemaCopy = join(schemaDir, 'schema.ts');
  const schemaText = readFileSync(join(scripts, 'schema.ts'), 'utf8');
  const rootImport = 'import { repoRoot as ROOT } from "../gen/utils.mts";';
  if (!schemaText.includes(rootImport)) throw new Error('schema.ts no longer imports repoRoot from gen/utils.mts');
  writeFileSync(schemaCopy, schemaText.replace(rootImport, `const ROOT = ${JSON.stringify(upstream)};`));
  let api;
  try {
    ({ api } = await import(pathToFileURL(schemaCopy).href));
  } finally {
    rmSync(schemaDir, { recursive: true, force: true });
  }
  const someList = api
    .nodes()
    .flatMap((node) => node.members)
    .find((member) => member.type.kind === 'list');
  // Lists are tsc-ts's NodeList (pos, end, nodes) and ModifierList; raw lists stay arrays.
  Object.getPrototypeOf(someList.type).formatTypeScript = function () {
    const element = this.elementType.formatTypeScript();
    if (this.listKind === 'raw') return `readonly ${element}[]`;
    if (this.listKind === 'ModifierList') return `ModifierList<${element}>`;
    return `NodeList<${element}>`;
  };

  const tsMembers = (node) => node.members.filter((member) => !member.isKindParam() && !member.noTS);
  const isInheritedFromTsBase = (member) => member.inherited && !!member.inheritedField && !member.inheritedField.noTS;
  const tsInterfaceMembers = (node) =>
    tsMembers(node).filter(
      (member) =>
        !isInheritedFromTsBase(member) ||
        member.hasTypeScriptOverride() ||
        redeclared.has(`${node.name}.${member.name}`),
    );
  const collapsedTextType = (name, type) =>
    name === 'text' && type.kind === 'list' && type.listKind === 'raw'
      ? type.elementType.formatTypeScript()
      : undefined;
  const isVariantNode = (node) => node.isMultiKind() && node.kindType.kind !== 'typeParameter';
  const goOnlyBases = new Set(
    api
      .bases()
      .filter((base) => base.isGoOnly())
      .map((base) => base.key),
  );
  const expandTsExtends = (exts) => {
    const result = [];
    const seen = new Set();
    const expand = (bases) => {
      for (const b of bases) {
        if (seen.has(b)) continue;
        seen.add(b);
        if (goOnlyBases.has(b)) {
          const base = api.getBase(b);
          if (base?.extends) expand(base.extendsKeys);
        } else result.push(b);
      }
    };
    expand(exts);
    return result;
  };
  const baseTsName = (base) => (typeof base === 'string' ? base : base.formatTypeScript());
  const resolveBaseExtends = (base) => {
    const exts = expandTsExtends(base.extendsKeys).map(baseTsName);
    return exts.length > 0 ? exts.join(', ') : 'Node';
  };
  const deriveNodeTsExtends = (node) => {
    const exts = expandTsExtends(node.extendsKeys).map(baseTsName);
    return exts.length > 0 ? exts.join(', ') : 'Node';
  };
  // Optional members are also `| undefined`: a node is a class instance, which has every member of its
  // kind whether it is set or not.
  const declare = (m, optional, node) => {
    const type =
      (node !== undefined ? memberTypes.get(`${node.name}.${m.name}`) : undefined) ??
      collapsedTextType(m.name, m.type) ??
      m.type.formatTypeScript();
    return `\n  readonly ${api.uncapitalize(m.name)}${optional ? `?: ${type} | undefined` : `: ${type}`};`;
  };
  const member = (m, node, kind) => {
    const variant = kind === undefined ? undefined : variantMembers.get(`${kind}.${m.name}`);
    if (variant === 'absent') return `\n  readonly ${api.uncapitalize(m.name)}?: undefined;`;
    if (variant === 'required') return declare(m, false, node);
    return declare(m, m.optional || nullable.has(`${node.name}.${m.name}`), node);
  };
  const baseMember = (m, base) => declare(m, m.optional || unstoredBaseFields.has(`${base.key}.${m.name}`));

  const parts = [];
  for (const { name, members } of api.kindAliases()) {
    parts.push(
      `export type ${name} = ${members.map((m) => (api.hasKindAlias(m) ? m : `SyntaxKind.${m}`)).join(' | ')};`,
    );
  }
  parts.push('');
  for (const base of api.bases()) {
    if (goOnlyBases.has(base.key)) continue;
    // Without TypeScript 7's brand members (`_expressionBrand`): node kinds discriminate, and an
    // implementation of these interfaces outside tsc-ts would have to copy the brand hierarchy.
    const fields = base.fields
      .filter((field) => !field.noTS)
      .map((field) => baseMember(field, base))
      .join('');
    parts.push(`export interface ${baseTsName(base)} extends ${resolveBaseExtends(base)} {${fields}\n}`);
  }
  parts.push('');
  const variants = [];
  for (const node of api.nodes()) {
    if (node.handWritten) continue;
    if (isVariantNode(node)) {
      for (const kind of node.kindTypes()) variants.push({ node, kind: kind.name });
      continue;
    }
    const typeParameters =
      node.typeParameters.length > 0
        ? `<${node.typeParameters.map((tp) => `${tp.name} extends ${tp.constraint}${tp.default ? ' = ' + tp.default : ''}`).join(', ')}>`
        : '';
    const members = tsInterfaceMembers(node)
      .filter((m) => !(m.rawType === 'SyntaxKind' && m.name === 'SyntaxKind'))
      .map((m) => member(m, node))
      .join('');
    parts.push(
      `export interface ${node.name}${typeParameters} extends ${deriveNodeTsExtends(node)} {\n  readonly kind: ${node.kindType.formatTypeScript()};${members}\n}`,
    );
  }
  parts.push('');
  for (const alias of api.nodeAliases()) {
    if (alias.isUnion) {
      const members = alias.unionMemberTypes.map((type) => type.formatTypeScript()).join(' | ');
      if (members !== '') parts.push(`export type ${alias.name} = ${members};`);
    } else if (alias.base) parts.push(`export type ${alias.name} = ${baseTsName(alias.base)};`);
  }
  parts.push('');
  for (const { node, kind } of variants) {
    const members = tsMembers(node)
      .filter((m) => !isInheritedFromTsBase(m) || m.hasTypeScriptOverride())
      .map((m) => member(m, node, kind))
      .join('');
    parts.push(
      `export interface ${kind} extends ${deriveNodeTsExtends(node)} {\n  readonly kind: SyntaxKind.${kind};${members}\n}`,
    );
  }
  for (const node of api.nodes()) {
    if (isVariantNode(node))
      parts.push(
        `export type ${node.name} = ${node
          .kindTypes()
          .map((kind) => kind.name)
          .join(' | ')};`,
      );
  }
  for (const node of api.nodes()) {
    for (const { name, typeArg } of node.instantiationAliases)
      parts.push(
        `export type ${name} = ${node.name}<${api.hasKindAlias(typeArg) ? typeArg : `SyntaxKind.${typeArg}`}>;`,
      );
  }
  for (const list of api.listAliases()) parts.push(`export type ${list.name} = NodeList<${list.elementTypeName}>;`);

  // Names the declarations use but don't declare: hand-written in ast.ts.
  const body = parts.join('\n');
  const declared = new Set([...body.matchAll(/^export (?:interface|type) (\w+)/gm)].map((m) => m[1]));
  const builtins = new Set(['any', 'boolean', 'never', 'null', 'number', 'string', 'undefined', 'unknown', 'void']);
  const fromEnums = new Set(['SyntaxKind', 'NodeFlags', 'ModifierFlags', 'TokenFlags']);
  const typeParameters = new Set(api.nodes().flatMap((node) => node.typeParameters.map((tp) => tp.name)));
  const referenced = new Set();
  for (const m of body.replace(/SyntaxKind\.\w+/g, 'SyntaxKind').matchAll(/\b[A-Z_]\w*\b/g))
    if (!typeParameters.has(m[0])) referenced.add(m[0]);
  const handWritten = [...referenced]
    .filter((name) => !declared.has(name) && !builtins.has(name) && !fromEnums.has(name) && /^[A-Z]/.test(name))
    .sort();
  const usedEnums = [...fromEnums].filter((name) => referenced.has(name)).sort();
  const header =
    notice('TypeScript tools/scripts/tsc/ast.json') +
    `\nimport type { ${handWritten.join(', ')} } from './ast.js';\n` +
    `import type { ${usedEnums.join(', ')} } from './enums.generated.js';\n\n`;
  return header + body + '\n';
}

const outputs = [
  ['enums.generated.ts', generateEnums()],
  ['compiler-options.generated.ts', generateCompilerOptions()],
  ['ast.generated.ts', await generateAst()],
];
let stale = false;
for (const [name, content] of outputs) {
  const path = join(libraryDir, name);
  if (check) {
    let current = '';
    try {
      current = readFileSync(path, 'utf8');
    } catch {}
    const formatted = execFileSync(join(repo, 'node_modules/.bin/oxfmt'), ['--stdin-filepath', path], {
      input: content,
      encoding: 'utf8',
    });
    if (current !== formatted) {
      console.error(`${name} is out of date: run node scripts/generate-api.mjs`);
      stale = true;
    }
  } else {
    writeFileSync(path, content);
    execFileSync(join(repo, 'node_modules/.bin/oxfmt'), [path]);
  }
}
if (stale) process.exitCode = 1;
