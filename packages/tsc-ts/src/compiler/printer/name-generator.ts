// Chooses the text of generated identifiers (`_a`, `_i`, `name_1`, …) while printing.
import {
  ClassExpression,
  ExportAssignment,
  type Node,
  NodeVisitor,
  PrivateIdentifier,
  SourceFile,
  StringLiteral,
  getLocals,
  getNextContainer,
  getText,
  isLocalsContainer,
} from '../ast.js';
import { SymbolFlags } from '../symbol.js';
import { getName } from '../ast.js';
import { getExternalModuleName } from '../ast-utilities.js';
import { SyntaxKind } from '../syntax-kind.js';
import type { EmitContext } from './emit-context.js';
import { GeneratedIdentifierFlags } from './emit-flags.js';
import {
  ensureLeadingHash,
  formatGeneratedName,
  makeIdentifierFromModuleName,
  removeLeadingHash,
} from './utilities.js';

const enum TempFlags {
  Auto = 0,
  CountMask = 0x0fffffff,
  /** `_i` is taken or preferred. */
  I = 0x10000000,
}

class NameScope {
  readonly next: NameScope | undefined;
  tempFlags: number;
  formattedNameTempFlags: Map<string, number> | undefined;
  reservedNames: Set<string> | undefined;

  constructor(next: NameScope | undefined) {
    this.next = next;
    this.tempFlags = TempFlags.Auto;
    this.formattedNameTempFlags = undefined;
    this.reservedNames = undefined;
  }
}

/** Where to look for name conflicts outside generated names. */
export abstract class NameGeneratorHost {
  /** The text of an identifier, private identifier or literal as printed. */
  abstract getTextOfNode(node: Node): string;
  /** Whether no identifier in the file (or global scope) has this name. */
  abstract isFileLevelUniqueName(name: string): boolean;
}

/** Whether no value declared in `container` or its nested containers has `name`, from the binder's locals. */
function isUniqueLocalName(name: string, container: Node): boolean {
  for (
    let node: Node | undefined = container;
    node !== undefined && isLocalsContainer(node);
    node = getNextContainer(node)
  ) {
    if (!isDescendantOf(node, container)) break;
    const locals = getLocals(node);
    const local = locals === undefined ? undefined : locals.get(name);
    if (local !== undefined && (local.flags & (SymbolFlags.Value | SymbolFlags.ExportValue | SymbolFlags.Alias)) !== 0)
      return false;
  }
  return true;
}

function isDescendantOf(node: Node, ancestor: Node): boolean {
  for (let current: Node | undefined = node; current !== undefined; current = current.parent)
    if (current === ancestor) return true;
  return false;
}

export class NameGenerator {
  readonly context: EmitContext;
  readonly host: NameGeneratorHost;
  private readonly nodeNames: Map<Node, string>;
  private readonly privateNodeNames: Map<Node, string>;
  private readonly autoGeneratedNames: Map<number, string>;
  private scope: NameScope | undefined;
  private privateScope: NameScope | undefined;
  private readonly generatedNames: Set<string>;

  constructor(context: EmitContext, host: NameGeneratorHost) {
    this.context = context;
    this.host = host;
    this.nodeNames = new Map<Node, string>();
    this.privateNodeNames = new Map<Node, string>();
    this.autoGeneratedNames = new Map<number, string>();
    this.scope = undefined;
    this.privateScope = undefined;
    this.generatedNames = new Set<string>();
  }

  pushScope(reuseTempVariableScope: boolean): boolean {
    this.privateScope = new NameScope(this.privateScope);
    if (!reuseTempVariableScope) this.scope = new NameScope(this.scope);
    return true;
  }

  popScope(reuseTempVariableScope: boolean): boolean {
    if (this.privateScope !== undefined) this.privateScope = this.privateScope.next;
    if (!reuseTempVariableScope && this.scope !== undefined) this.scope = this.scope.next;
    return true;
  }

  private ensureScope(privateName: boolean): NameScope {
    if (privateName) {
      if (this.privateScope === undefined) this.privateScope = new NameScope(undefined);
      return this.privateScope;
    }
    if (this.scope === undefined) this.scope = new NameScope(undefined);
    return this.scope;
  }

  private getTempFlags(privateName: boolean, key: string): number {
    const scope = privateName ? this.privateScope : this.scope;
    if (scope === undefined) return TempFlags.Auto;
    if (key.length === 0) return scope.tempFlags;
    const flags = scope.formattedNameTempFlags === undefined ? undefined : scope.formattedNameTempFlags.get(key);
    return flags === undefined ? TempFlags.Auto : flags;
  }

  private setTempFlags(privateName: boolean, key: string, flags: number): boolean {
    const scope = this.ensureScope(privateName);
    if (key.length === 0) scope.tempFlags = flags;
    else {
      if (scope.formattedNameTempFlags === undefined) scope.formattedNameTempFlags = new Map<string, number>();
      scope.formattedNameTempFlags.set(key, flags);
    }
    return true;
  }

  private reserveName(name: string, privateName: boolean, scoped: boolean, temp: boolean): boolean {
    const scope = this.ensureScope(privateName);
    if (privateName || scoped) {
      if (scope.reservedNames === undefined) scope.reservedNames = new Set<string>();
      scope.reservedNames.add(name);
    } else if (!temp) this.generatedNames.add(name);
    return true;
  }

  /** The text of a name: generated if it has auto-generate info, else its own text. */
  generateName(name: Node): string {
    const info = this.context.autoGenerate.get(name);
    if (info === undefined) return this.host.getTextOfNode(name);
    if ((info.flags & GeneratedIdentifierFlags.KindMask) === GeneratedIdentifierFlags.Node)
      return this.generateNameForNodeCached(
        this.context.getNodeForGeneratedName(name),
        name instanceof PrivateIdentifier,
        info.flags,
        info.prefix,
        info.suffix,
      );
    const cached = this.autoGeneratedNames.get(info.id);
    if (cached !== undefined) return cached;
    const generated = this.makeName(name);
    this.autoGeneratedNames.set(info.id, generated);
    return generated;
  }

  private generateNameForNodeCached(
    node: Node,
    privateName: boolean,
    flags: GeneratedIdentifierFlags,
    prefix: string,
    suffix: string,
  ): string {
    const cache = privateName ? this.privateNodeNames : this.nodeNames;
    const cached = cache.get(node);
    if (cached !== undefined) return cached;
    const name = this.generateNameForNode(node, privateName, flags, prefix, suffix);
    cache.set(node, name);
    return name;
  }

  private generateNameForNode(
    node: Node,
    privateName: boolean,
    flags: GeneratedIdentifierFlags,
    prefix: string,
    suffix: string,
  ): string {
    switch (node.kind) {
      case SyntaxKind.Identifier:
      case SyntaxKind.PrivateIdentifier:
        return this.makeUniqueName(
          this.host.getTextOfNode(node),
          false,
          (flags & GeneratedIdentifierFlags.Optimistic) !== 0,
          (flags & GeneratedIdentifierFlags.ReservedInNestedScopes) !== 0,
          privateName,
          prefix,
          suffix,
        );
      case SyntaxKind.ModuleDeclaration:
      case SyntaxKind.EnumDeclaration: {
        const name = this.host.getTextOfNode(getName(node)!);
        if (isUniqueLocalName(name, node)) return name;
        return this.makeUniqueName(name, false, false, false, false, '', '');
      }
      case SyntaxKind.ImportDeclaration:
      case SyntaxKind.JSImportDeclaration:
      case SyntaxKind.ExportDeclaration: {
        const specifier = getExternalModuleName(node);
        const base = specifier instanceof StringLiteral ? makeIdentifierFromModuleName(specifier.text) : 'module';
        return this.makeUniqueName(base, false, false, false, false, '', '');
      }
      case SyntaxKind.FunctionDeclaration:
      case SyntaxKind.ClassDeclaration: {
        const name = getName(node);
        if (name !== undefined) return this.generateNameForNode(name, false, flags, '', '');
        return this.makeUniqueName('default', false, false, false, false, '', '');
      }
      case SyntaxKind.ExportAssignment:
        if (node instanceof ExportAssignment) return this.makeUniqueName('default', false, false, false, false, '', '');
        break;
      case SyntaxKind.ClassExpression:
        if (node instanceof ClassExpression) return this.makeUniqueName('class', false, false, false, false, '', '');
        break;
      case SyntaxKind.MethodDeclaration:
      case SyntaxKind.GetAccessor:
      case SyntaxKind.SetAccessor: {
        const name = getName(node);
        if (name !== undefined && name.kind === SyntaxKind.Identifier)
          return this.generateNameForNodeCached(name, privateName, GeneratedIdentifierFlags.None, prefix, suffix);
        return this.makeTempVariableName(TempFlags.Auto, false, privateName, prefix, suffix);
      }
      case SyntaxKind.ComputedPropertyName:
        return this.makeTempVariableName(TempFlags.Auto, true, privateName, prefix, suffix);
    }
    return this.makeTempVariableName(TempFlags.Auto, false, privateName, prefix, suffix);
  }

  private makeName(name: Node): string {
    const info = this.context.autoGenerate.get(name);
    if (info !== undefined) {
      const reserved = (info.flags & GeneratedIdentifierFlags.ReservedInNestedScopes) !== 0;
      switch (info.flags & GeneratedIdentifierFlags.KindMask) {
        case GeneratedIdentifierFlags.Auto:
          return this.makeTempVariableName(
            TempFlags.Auto,
            reserved,
            name instanceof PrivateIdentifier,
            info.prefix,
            info.suffix,
          );
        case GeneratedIdentifierFlags.Loop:
          return this.makeTempVariableName(TempFlags.I, reserved, false, info.prefix, info.suffix);
        case GeneratedIdentifierFlags.Unique:
          return this.makeUniqueName(
            getText(name),
            (info.flags & GeneratedIdentifierFlags.FileLevel) !== 0,
            (info.flags & GeneratedIdentifierFlags.Optimistic) !== 0,
            reserved,
            name instanceof PrivateIdentifier,
            info.prefix,
            info.suffix,
          );
      }
    }
    return this.host.getTextOfNode(name);
  }

  private makeTempVariableName(
    flags: TempFlags,
    reservedInNestedScopes: boolean,
    privateName: boolean,
    prefix: string,
    suffix: string,
  ): string {
    const simple = prefix.length === 0 && suffix.length === 0;
    let key = '';
    if (!simple) {
      key = formatGeneratedName(privateName, prefix, '', suffix);
      if (privateName) key = ensureLeadingHash(key);
    }
    let tempFlags = this.getTempFlags(privateName, key);
    if (flags !== 0 && (tempFlags & flags) === 0) {
      const fullName = formatGeneratedName(privateName, prefix, '_i', suffix);
      if (this.isUniqueName(fullName, privateName)) {
        tempFlags |= flags;
        this.reserveName(fullName, privateName, reservedInNestedScopes, true);
        this.setTempFlags(privateName, key, tempFlags);
        return fullName;
      }
    }
    for (;;) {
      const count = tempFlags & TempFlags.CountMask;
      tempFlags++;
      // Skip `_i` and `_n`.
      if (count !== 8 && count !== 13) {
        const name = count < 26 ? '_' + String.fromCharCode(0x61 + count) : '_' + (count - 26);
        const fullName = formatGeneratedName(privateName, prefix, name, suffix);
        if (this.isUniqueName(fullName, privateName)) {
          this.reserveName(fullName, privateName, reservedInNestedScopes, true);
          this.setTempFlags(privateName, key, tempFlags);
          return fullName;
        }
      }
    }
  }

  private makeUniqueName(
    baseName: string,
    fileLevel: boolean,
    optimistic: boolean,
    scoped: boolean,
    privateName: boolean,
    prefix: string,
    suffix: string,
  ): string {
    baseName = removeLeadingHash(baseName);
    if (optimistic) {
      const fullName = formatGeneratedName(privateName, prefix, baseName, suffix);
      if (this.checkUniqueName(fullName, privateName, fileLevel)) {
        this.reserveName(fullName, privateName, scoped, false);
        return fullName;
      }
    }
    if (baseName.length > 0 && baseName.charCodeAt(baseName.length - 1) !== 0x5f) baseName += '_';
    for (let i = 1; ; i++) {
      const fullName = formatGeneratedName(privateName, prefix, baseName + i, suffix);
      if (this.checkUniqueName(fullName, privateName, fileLevel)) {
        this.reserveName(fullName, privateName, scoped, false);
        return fullName;
      }
    }
  }

  makeFileLevelOptimisticUniqueName(name: string): string {
    return this.makeUniqueName(name, true, true, false, false, '', '');
  }

  private checkUniqueName(name: string, privateName: boolean, fileLevel: boolean): boolean {
    return fileLevel ? this.host.isFileLevelUniqueName(name) : this.isUniqueName(name, privateName);
  }

  private isUniqueName(name: string, privateName: boolean): boolean {
    return this.host.isFileLevelUniqueName(name) && !this.isReservedName(name, privateName);
  }

  private isReservedName(name: string, privateName: boolean): boolean {
    if (this.generatedNames.has(name)) return true;
    for (let scope = privateName ? this.privateScope : this.scope; scope !== undefined; scope = scope.next)
      if (scope.reservedNames !== undefined && scope.reservedNames.has(name)) return true;
    return false;
  }
}

// The names used in recently emitted files, kept apart from the files, which are shared and read-only.
const identifierSets = new Map<SourceFile, Set<string>>();

/** Forgets the files of earlier emits. */
export function forgetIdentifierSets(): void {
  identifierSets.clear();
}

/** Collects the texts of a file's identifiers, private names and literals: the names its generated names avoid. */
class NameTextCollector extends NodeVisitor {
  readonly texts = new Set<string>();

  visitNode(node: Node): boolean {
    switch (node.kind) {
      case SyntaxKind.Identifier:
      case SyntaxKind.PrivateIdentifier:
      case SyntaxKind.StringLiteral:
      case SyntaxKind.NumericLiteral:
      case SyntaxKind.BigIntLiteral:
      case SyntaxKind.NoSubstitutionTemplateLiteral:
        this.texts.add(getText(node));
    }
    node.forEachChild(this);
    return false;
  }
}

/** Whether no identifier, private name or literal in `file` has the text `name`. */
export function isFileLevelUniqueName(file: SourceFile, name: string): boolean {
  let set = identifierSets.get(file);
  if (set === undefined) {
    if (identifierSets.size >= 16) identifierSets.clear();
    const collector = new NameTextCollector();
    file.forEachChild(collector);
    set = collector.texts;
    identifierSets.set(file, set);
  }
  return !set.has(name);
}
